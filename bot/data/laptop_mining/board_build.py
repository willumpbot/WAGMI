"""Regenerate the board's idea list from live data, so it cannot go stale.

WHY. The board artifact hard-coded three ideas as a JS literal. The server runs Opus on a ~11.5h
cadence, so that list goes stale the moment new ideas land, and keeping it current by hand is a
chore nobody will do. The server asked for exactly this fix (reply 51, item 2) and specified the
filter: only ideas whose `result.status` is waiting/open.

WHAT IT DOES. Rewrites the block between `// IDEAS-START` and `// IDEAS-END` in the board HTML
from `server_exports/ai_plans.json`. Everything else in the page is untouched, so the design and
the capability wiring are not at risk from a data refresh.

The ids matter: they key the `decisions` collection in the artifact's store, so a decision the
owner already recorded stays attached to its idea across rebuilds. An idea that leaves the open
list simply stops being rendered; its recorded decision is not deleted.
"""
import io
import json
import os
import sys

MINING = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(MINING, "server_exports", "ai_plans.json")
OPEN_STATES = ("", "open", "waiting", "pending", "live", "filled")

START = "  // IDEAS-START"
END = "  // IDEAS-END"


def js(s):
    """Quote for a JS single-quoted string. The reason text is model-written prose and can
    contain anything, so escape rather than trust it."""
    return (str(s).replace("\\", "\\\\").replace('"', '\\"')
            .replace("\n", " ").replace("\r", " ").strip())


def num(x, nd=0):
    try:
        v = float(x)
    except (TypeError, ValueError):
        return "?"
    return ("{:,.%df}" % nd).format(v)


def is_open(it):
    r = it.get("result")
    if isinstance(r, dict):
        return str(r.get("status") or "").lower() in OPEN_STATES
    return str(r or "").lower() in OPEN_STATES


def build_ideas():
    if not os.path.exists(SRC):
        return None, "SOURCE-MISSING: ai_plans.json absent"
    try:
        d = json.load(io.open(SRC, encoding="utf-8"))
    except (ValueError, OSError) as e:
        return None, "SOURCE-UNREADABLE: %s" % str(e)[:80]
    items = d.get("ideas") if isinstance(d, dict) else d
    if not isinstance(items, list):
        return None, "SOURCE-SHAPE-UNKNOWN: no list of ideas"
    live = [it for it in items if isinstance(it, dict) and it.get("id") and is_open(it)]
    rows = []
    for it in live:
        px = it.get("entry")
        nd = 0 if (isinstance(px, (int, float)) and abs(px) >= 100) else 2
        rows.append(
            "    { id: \"%s\", coin: \"%s\", side: \"%s\", entry: \"%s\", stop: \"%s\",\n"
            "      target: \"%s\", lev: \"%sx\",\n"
            "      setup: \"%s\",\n"
            "      why: \"%s\" }"
            % (js(it["id"]), js(it.get("coin") or "?"), js((it.get("side") or "?").upper()),
               num(it.get("entry"), nd), num(it.get("stop"), nd), num(it.get("target"), nd),
               num(it.get("leverage"), 0),
               js(it.get("setup") or "no setup given"),
               js(it.get("reason") or "no reasoning given")))
    body = "  var IDEAS = [\n" + ",\n".join(rows) + "\n  ];\n" if rows else "  var IDEAS = [];\n"
    return body, "%d open of %d total" % (len(live), len(items))


def main():
    board = sys.argv[1] if len(sys.argv) > 1 else None
    if not board or not os.path.exists(board):
        print("usage: board_build.py <path to nunu_board.html>")
        return 2
    body, note = build_ideas()
    print("ai_plans: %s" % note)
    if body is None:
        print("REFUSING to rewrite the board: the source could not be read.")
        print("Leaving the existing list in place -- a stale list beats an empty one, and an")
        print("unreadable source is not a signal that there are no open ideas.")
        return 1
    s = io.open(board, encoding="utf-8").read()
    i, j = s.find(START), s.find(END)
    if i < 0 or j < 0 or j <= i:
        print("markers not found in %s -- not touching it" % board)
        return 1
    head = s[:i + len(START)]
    tail = s[j:]
    out = head + " (generated by board_build.py from ai_plans.json -- do not hand-edit)\n" \
        + body + tail
    if out == s:
        print("no change")
        return 0
    io.open(board, "w", encoding="utf-8").write(out)
    print("board idea list regenerated (%d bytes)" % len(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
